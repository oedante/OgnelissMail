// lib/core/utils/avatar_colors.dart
// Цвета кружков с буквой (аватар без фото). Одна палитра на всё приложение:
// раньше в цепочке писем были пастельные Material 300 (белая буква на
// жёлтом/салатовом не читалась), а у контактов в «Кому» — случайный цвет из
// хэша адреса (мог выйти кислотно-зелёным или почти чёрным) — аудит цветов
// 10.10.2026.
//
// Приглушённые средние тона: белая буква — ≥ 4.5:1 на каждом, и на тёмном
// фоне кружок отличим (≥ 3:1).

/// Значения ARGB (без зависимости от Flutter — нужны и в моделях данных).
const kAvatarColorValues = <int>[
  0xFFB0504B, 0xFF467E59, 0xFF456EA3,
  0xFF9E6B2A, 0xFF7E5A9E, 0xFF357F7A,
  0xFFA3536F, 0xFF5F7A33, 0xFF555FA0,
  0xFF8A7424, 0xFF37789A, 0xFF7D6456,
];

/// Цвет кружка для адреса или имени [key] — постоянный для одного ключа.
int avatarColorValue(String key) =>
    kAvatarColorValues[key.toLowerCase().hashCode.abs() % kAvatarColorValues.length];
