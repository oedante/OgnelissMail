// lib/widgets/common/chrome_visibility.dart
//
// Видимость вспомогательных панелей при прокрутке.
//
// На телефоне экран маленький: кнопка «Написать» и нижняя навигация занимают
// заметную его часть. Пока человек читает список, они не нужны — прячем.
// Как только он тянет список вверх (ищет действие) — возвращаем.
//
// Состояние вынесено в провайдер, потому что прокрутка происходит в экране
// списка, а прячутся элементы в оболочке приложения (FAB, нижняя навигация).
//
// На широких экранах скрывать нечего: места достаточно, и «прыгающие» панели
// только раздражают — поэтому там провайдер всегда отдаёт true.

import 'package:flutter_riverpod/legacy.dart';

final chromeVisibleProvider = StateProvider<bool>((ref) => true);
