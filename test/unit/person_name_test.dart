// Краткое имя «Фамилия И.О.» для «Людей в цитатах» (1.10.5, просьба
// владельца 03.11.2026): все порядки слов из писем, отчество и без него;
// неясное остаётся как в письме.
import 'package:flutter_test/flutter_test.dart';
import 'package:ogneliss/core/utils/person_name.dart';

void main() {
  String? s(String n) => PersonName.short(n);

  test('Фамилия Имя Отчество → Фамилия И.О.', () {
    expect(s('Зибров Дмитрий Николаевич'), 'Зибров Д.Н.');
    expect(s('Зеленина Оксана Андреевна'), 'Зеленина О.А.');
    expect(s('Хабиров Ренат Фанильевич'), 'Хабиров Р.Ф.');
    expect(s('Ганиев Руслан Рамилевич'), 'Ганиев Р.Р.');
    expect(s('Карпович Андрей Сергеевич'), 'Карпович А.С.');
    expect(s('Петрова Анна Ильинична'), 'Петрова А.И.');
    expect(s('ЗИБРОВ ДМИТРИЙ НИКОЛАЕВИЧ'), 'ЗИБРОВ Д.Н.');
    expect(s('  Зибров   Дмитрий  Николаевич '), 'Зибров Д.Н.');
  });

  test('Имя Отчество Фамилия → Фамилия И.О.', () {
    expect(s('Дмитрий Николаевич Зибров'), 'Зибров Д.Н.');
    expect(s('Андрей Сергеевич Карпович'), 'Карпович А.С.');
  });

  test('без отчества → Фамилия И., порядок слов — по имени и окончанию фамилии', () {
    expect(s('Ганиев Руслан'), 'Ганиев Р.');
    expect(s('Олег Ермишин'), 'Ермишин О.');
    expect(s('Ермишин Олег'), 'Ермишин О.');
    expect(s('Марина Зеленина'), 'Зеленина М.');
    expect(s('Зеленина Марина'), 'Зеленина М.');
    expect(s('Бабич Олег'), 'Бабич О.');
    expect(s('Анна-Мария Петрова'), 'Петрова А.-М.');
    expect(s('Жаринов Ферапонт'), 'Жаринов Ф.');
  });

  test('отчество двумя словами', () {
    expect(s('Мамедов Эльчин Акиф оглы'), 'Мамедов Э.А.');
  });

  test('латиница — только с отчеством', () {
    expect(s('Peredery Sergey Anatolyevich'), 'Peredery S.A.');
    expect(s('Sergey Anatolyevich Peredery'), 'Peredery S.A.');
    expect(s('John Smith'), isNull);
    expect(s('Ivan N'), isNull);
    expect(s('John Fitzgerald Kennedy'), isNull);
  });

  test('не сокращается: одно слово, уже кратко, адрес, без фамилии, неясный порядок', () {
    expect(s('Зибров'), isNull);
    expect(s('Зибров Д.Н.'), isNull);
    expect(s('Зибров Д. Н.'), isNull);
    expect(s('user@example.com'), isNull);
    expect(s('Сергей Анатольевич'), isNull);
    expect(s('Нестор Махно'), isNull);
    expect(s('Отдел кадров 2'), isNull);
    expect(s('Служба поддержки (ИТ)'), isNull);
    expect(s('Иванов Иван Иванович Петров Сидоров'), isNull);
  });

  test('показ: полностью или кратко', () {
    expect(PersonName.display('Зибров Дмитрий Николаевич', shortForm: false), 'Зибров Дмитрий Николаевич');
    expect(PersonName.display('Зибров Дмитрий Николаевич', shortForm: true), 'Зибров Д.Н.');
    expect(PersonName.display('Нестор Махно', shortForm: true), 'Нестор Махно');
  });
}
