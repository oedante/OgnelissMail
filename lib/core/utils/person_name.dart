// lib/core/utils/person_name.dart
//
// Краткое имя человека: «Фамилия И.О.», без отчества — «Фамилия И.»
// (1.10.5, просьба владельца 03.11.2026 для «Людей в цитатах»: «сделать два
// варианта "Фамилия И.О." или "Фамилия И." (там где отчества нет) и полный
// вариант. По умолчанию сокращённый»).
//
// Порядок слов в именах из писем разный: в адресной книге Exchange —
// «Фамилия Имя Отчество», у Gmail и в подписях — «Имя Фамилия», иногда
// «Имя Отчество Фамилия». Отчество узнаётся по окончанию (-вич, -вна,
// -ична, -ич, «оглы», «кызы»), имя — по списку частых имён, фамилия — по
// окончанию (-ов, -ев, -ин, -ский…). Не ясно, где фамилия, — имя остаётся
// как в письме: лучше длинно, чем «Олег Е.» вместо «Ермишин О.».
// Латиница — только с отчеством («Peredery Sergey Anatolyevich»):
// «John Smith» сокращать не принято, а порядок слов не угадать.

class PersonName {
  PersonName._();

  static final _cyr = RegExp(r'^[А-Яа-яЁё]+(?:-[А-Яа-яЁё]+)*$');
  static final _lat = RegExp(r'^[A-Za-z]+(?:-[A-Za-z]+)*$');
  static final _initial = RegExp(r'^\p{L}\.(?:-?\p{L}\.)*$', unicode: true);

  /// Отчество одним словом.
  static final _patrCyr = RegExp(r'(вич|вна|ична|чна|ич)$');
  static final _patrLat = RegExp(r'(vich|vitch|vna|ichna)$');

  /// Тюркское отчество вторым словом: «Акиф оглы».
  static const _patrTail = {'оглы', 'кызы', 'улы', 'гызы', 'ogly', 'oglu', 'kyzy', 'qizi'};

  /// Окончания фамилий (именительный падеж, мужские и женские).
  static final _surname = RegExp(
      r'(ов|ев|ёв|ин|ын|ова|ева|ёва|ина|ына|ский|цкий|ская|цкая|ской|цкой|ых|их|енко|ук|юк|ян|дзе|швили)$');

  /// Частые имена (русские, татарские, башкирские, кавказские) — по ним
  /// видно, что первое слово не фамилия: «Олег Ермишин», «Марина Зеленина».
  static const _given = {
    // мужские
    'александр', 'алексей', 'анатолий', 'андрей', 'антон', 'аркадий', 'арсений', 'артём', 'артем',
    'борис', 'вадим', 'валентин', 'валерий', 'василий', 'виктор', 'виталий', 'владимир', 'владислав',
    'вячеслав', 'геннадий', 'георгий', 'герман', 'глеб', 'григорий', 'даниил', 'данил', 'денис',
    'дмитрий', 'евгений', 'егор', 'иван', 'игорь', 'илья', 'кирилл', 'константин', 'лев', 'леонид',
    'максим', 'марк', 'матвей', 'михаил', 'никита', 'николай', 'олег', 'павел', 'пётр', 'петр',
    'роман', 'ростислав', 'святослав', 'семён', 'семен', 'сергей', 'станислав', 'степан', 'тимофей',
    'фёдор', 'федор', 'филипп', 'эдуард', 'юрий', 'ярослав', 'яков', 'эрик', 'всеволод', 'захар',
    'айдар', 'азат', 'альберт', 'альфред', 'артур', 'булат', 'дамир', 'ильдар', 'ильнур', 'ильшат',
    'ильдус', 'ирек', 'камиль', 'марат', 'наиль', 'радик', 'рамиль', 'ренат', 'ринат', 'рифат',
    'руслан', 'рустам', 'рустем', 'тагир', 'тимур', 'фарид', 'шамиль', 'эльдар', 'эмиль', 'айрат',
    'арсен', 'армен', 'ашот', 'гамлет', 'давид', 'заур', 'ислам', 'мурат', 'расул', 'тигран',
    // женские
    'александра', 'алина', 'алла', 'алёна', 'алена', 'анастасия', 'ангелина', 'анна', 'антонина',
    'валентина', 'валерия', 'варвара', 'вера', 'вероника', 'виктория', 'галина', 'дарья', 'диана',
    'ева', 'евгения', 'екатерина', 'елена', 'елизавета', 'жанна', 'зинаида', 'зоя', 'инна', 'ирина',
    'карина', 'кира', 'кристина', 'ксения', 'лариса', 'лидия', 'любовь', 'людмила', 'маргарита',
    'марина', 'мария', 'надежда', 'наталья', 'наталия', 'нина', 'оксана', 'ольга', 'полина', 'раиса',
    'светлана', 'софья', 'софия', 'тамара', 'татьяна', 'ульяна', 'юлия', 'яна', 'эльвира', 'регина',
    'айгуль', 'альбина', 'альфия', 'венера', 'гульнара', 'гузель', 'гульшат', 'динара', 'дина',
    'зарина', 'зульфия', 'ильмира', 'лейла', 'лилия', 'лиана', 'лиля', 'резеда', 'розалия',
    'эльмира', 'ляйсан', 'алсу', 'асель', 'камила',
  };

  /// Краткое имя или null, если сокращать не нужно или нельзя (одно слово,
  /// адрес, уже «Фамилия И.О.», порядок слов не ясен).
  static String? short(String name) {
    final t = name.replaceAll(RegExp(r'\s+'), ' ').trim();
    if (t.isEmpty || t.contains('@') || RegExp(r'[\d()\[\]<>]').hasMatch(t)) return null;
    final w = t.split(' ');
    if (w.length < 2 || w.length > 4) return null;
    if (w.skip(1).any(_initial.hasMatch)) return null; // уже «Зибров Д.Н.»
    final cyr = w.every(_cyr.hasMatch);
    if (!cyr && !w.every(_lat.hasMatch)) return null;
    final patr = cyr ? _patrCyr : _patrLat;
    bool isPatr(String s) => patr.hasMatch(s.toLowerCase());
    bool isGiven(String s) => cyr && _given.contains(s.toLowerCase());
    bool isSurname(String s) => cyr && _surname.hasMatch(s.toLowerCase());

    // «Мамедов Эльчин Акиф оглы»: отчество — два слова.
    if (w.length == 4) {
      if (!_patrTail.contains(w[3].toLowerCase())) return null;
      return _fio(w[0], w[1], w[2]);
    }
    if (w.length == 3) {
      // «Дмитрий Николаевич Зибров» — имя первым, отчество вторым.
      if (isPatr(w[1]) && (isGiven(w[0]) || !isPatr(w[2]))) return _fio(w[2], w[0], w[1]);
      if (isPatr(w[2])) return _fio(w[0], w[1], w[2]);
      return null;
    }
    // Два слова. «Сергей Анатольевич» — без фамилии, как есть.
    if (isPatr(w[1]) && !isSurname(w[0])) return null;
    if (!cyr) return null;
    final g0 = isGiven(w[0]), g1 = isGiven(w[1]);
    if (g0 && !g1) return _fio(w[1], w[0], null); // «Олег Ермишин»
    if (g1 && !g0) return _fio(w[0], w[1], null); // «Ганиев Руслан»
    final s0 = isSurname(w[0]), s1 = isSurname(w[1]);
    if (s0 && !s1) return _fio(w[0], w[1], null);
    if (s1 && !s0) return _fio(w[1], w[0], null);
    return null;
  }

  /// Имя для показа: краткое, если [shortForm] и сократить можно.
  static String display(String name, {required bool shortForm}) =>
      shortForm ? (short(name) ?? name) : name;

  static String _fio(String surname, String given, String? patronymic) =>
      '$surname ${_init(given)}${patronymic == null ? '' : _init(patronymic)}';

  /// «Анна-Мария» → «А.-М.», «иван» → «И.».
  static String _init(String word) =>
      word.split('-').where((p) => p.isNotEmpty).map((p) => '${p[0].toUpperCase()}.').join('-');
}
